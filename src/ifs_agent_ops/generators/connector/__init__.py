"""Connector generator (Phase 9): approved capabilities -> a Power Platform custom connector definition.

Pipeline (plan §5a): **select** (operations referenced by approved capabilities, matched to the
pinned ``$openapi?V2``) -> **compatibility transforms** -> **annotate** -> **prune** -> **validate**,
then write into ``<package>/power-platform/connector/``:

- ``apiDefinition.swagger.json``: Swagger 2.0, compact UTF-8 JSON (the bytes measured are the bytes written);
- ``apiProperties.json``: connector properties that do not depend on an environment;
- ``operation-ids.yaml``: the **stable operationId map** (published flows call connector operations by
  operationId, so an id never changes or gets reused once generated);
- ``report.md``: selection, transforms, size report, deployment items and provenance.

Deterministic and offline: pinned metadata only, no timestamps, no IFS or Power Platform calls.
Environment-specific values are not generated: the host stays the ``ifs.example`` placeholder and the
connection's authentication and gateway settings are deployment state, resolved per target in
Phase 10 (roadmap §7, assumptions 2 and 5). The definition is **not deployment-validated** until
runtime validation (Phase 11) succeeds.
"""
from __future__ import annotations

import copy
import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

import yaml

from ifs_agent_ops.generators.connector import annotate, compat, prune, validate
from ifs_agent_ops.generators.connector.select import Selected, match_spec, selected_operations
from ifs_agent_ops.generators.gating import GenerationRefused
from ifs_agent_ops.ifs.metadata import snapshot as snap
from ifs_agent_ops.ifs.metadata.edmx import parse_edmx
from ifs_agent_ops.ifs.paths import PROJECTION_ROOT
from ifs_agent_ops.operations.capability_store import load_capabilities
from ifs_agent_ops.operations.store import load_operations
from ifs_agent_ops.recordings.redact import PLACEHOLDER_IFS_HOST
from ifs_agent_ops.workspace.package import Package

GENERATOR = "ifs-agent-ops connector generator v1"
DEFINITION_FILE = "apiDefinition.swagger.json"
PROPERTIES_FILE = "apiProperties.json"
MAP_FILE = "operation-ids.yaml"
REPORT_FILE = "report.md"
FILES = (DEFINITION_FILE, PROPERTIES_FILE, MAP_FILE, REPORT_FILE)
_MAP_HEADER = (f"# Generated by {GENERATOR}; the stable operationId map of this connector.\n"
               "# Published flows call connector operations by operationId: an id never changes, and a\n"
               "# retired id is never reused. Regenerate with: ifs-agent-ops connector generate --package <p>\n")


def connector_dir(package: Package) -> Path:
    return package.root / "power-platform" / "connector"


@dataclass
class Entry:
    sel: Selected
    operation_id: str
    method: str
    path: str
    params: dict[str, str] = field(default_factory=dict)  # connector parameter -> canonical parameter
    renamed: list[str] = field(default_factory=list)
    literals: list[str] = field(default_factory=list)
    aliases: list[str] = field(default_factory=list)


@dataclass
class Built:
    files: dict[str, str]
    entries: list[Entry]
    size: validate.SizeReport
    stats: dict
    skipped: list[str]
    retired: list[str]


@dataclass
class ConnectorResult:
    path: Path
    action: str  # created | updated | unchanged | would-create | would-update | refused
    message: str = ""


@dataclass
class Generation:
    results: list[ConnectorResult]
    built: Optional[Built] = None
    errors: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.errors


# ── inputs ───────────────────────────────────────────────────────────────────

def _pinned(package: Package, projection: str) -> tuple[dict, object, dict]:
    folder = snap.snapshot_dir(package, projection)
    manifest_path = folder / snap.SNAPSHOT_FILE
    if not (folder / snap.OPENAPI_FILE).exists() or not manifest_path.exists():
        raise GenerationRefused(f"no pinned $openapi for {projection}; run `ifs-agent-ops metadata snapshot "
                                f"--package {package.name} --projection {projection}`")
    manifest = yaml.safe_load(manifest_path.read_text(encoding="utf-8")) or {}
    for name in (snap.METADATA_FILE, snap.OPENAPI_FILE):
        data = (folder / name).read_bytes()
        pinned = (manifest.get("files") or {}).get(name, {}).get("sha256")
        if pinned != hashlib.sha256(data).hexdigest():
            raise GenerationRefused(f"{projection}/{name} does not match its snapshot.yaml hash; re-snapshot it")
    spec = json.loads((folder / snap.OPENAPI_FILE).read_text(encoding="utf-8"))
    if str(spec.get("swagger")) != "2.0":
        raise GenerationRefused(f"{projection}/{snap.OPENAPI_FILE} is not Swagger 2.0")
    edmx = parse_edmx((folder / snap.METADATA_FILE).read_text(encoding="utf-8"))
    return spec, edmx, manifest


def _read_map(package: Package) -> Optional[dict]:
    path = connector_dir(package) / MAP_FILE
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    if GENERATOR.split(" v")[0] not in text:
        raise GenerationRefused(f"{MAP_FILE} exists and was not generated; not overwriting it")
    return yaml.safe_load(text) or {}


# ── assembly ─────────────────────────────────────────────────────────────────

def _operation_object(sel: Selected, edmx, stats: dict) -> tuple[dict, Entry]:
    op = sel.op
    rendered = compat.render_path(op)
    types = {pp.name: pp.type for pp in op.path_parameters}
    obj = copy.deepcopy(sel.spec_op)
    kept = []
    for p in obj.get("parameters", []):
        if p.get("in") in ("path", "header") or str(p.get("name", "")).startswith("@"):
            continue  # rebuilt from the canonical operation below
        kept.append(p)
    params: list[dict] = []
    for pp in rendered.params:
        if pp.logical not in types:
            raise GenerationRefused(f"{op.id}: path placeholder {pp.logical} is not a canonical path parameter")
        params.append(compat.path_parameter(pp, types[pp.logical]))
    for alias in rendered.aliases:
        t = types.get(alias)
        spec_alias = next((p for p in sel.spec_op.get("parameters", []) if p.get("name") == "@" + alias), {})
        params.append({"name": "@" + alias, "in": "query", "required": True, "type": "string", "x-ms-summary": alias,
                       "description": f"JSON value of {t.edm if t else alias} (parameter alias; sent as "
                                      f"@{alias}=<json> in the query string)."
                                      + (f" {spec_alias['description']}." if spec_alias.get("description") else "")})
    for h in op.headers:
        params.append({"name": h.name, "in": "header", "required": h.required, "type": "string",
                       "x-ms-summary": h.name, "description": h.reason})
    for p in kept:
        if "$ref" not in p:
            p.setdefault("x-ms-summary", p.get("name", "").lstrip("$@"))
    obj["parameters"] = params + kept
    obj["operationId"] = compat.operation_id(op)
    if op.title:
        obj["summary"] = op.title
    if op.description:
        obj["description"] = " ".join(op.description.split())
    for p in obj["parameters"]:
        stats["links_removed"] += annotate.strip_links(p)
        stats["arrays_converted"] += compat.array_query_to_string(p)
    if op.method == "GET":
        stats["annotations"] += annotate.annotate_read(obj, op, edmx)
    entry = Entry(sel=sel, operation_id=obj["operationId"], method=op.method,
                  path=f"/{op.projection}.svc{rendered.path}",
                  params={pp.name: pp.logical for pp in rendered.params if pp.name != pp.logical},
                  renamed=rendered.renamed, literals=[pp.name for pp in rendered.params if pp.literal],
                  aliases=rendered.aliases)
    return obj, entry


def build(package: Package, max_bytes: int = validate.DEFAULT_MAX_BYTES) -> Built:
    caps = load_capabilities(package)
    ops = load_operations(package)
    selected, skipped = selected_operations(caps, ops)
    projections = sorted({s.op.projection for s in selected})
    pinned = {p: _pinned(package, p) for p in projections}
    stats = {"links_removed": 0, "arrays_converted": 0, "annotations": 0}

    components: dict[str, dict] = {"definitions": {}, "parameters": {}, "responses": {}}
    tags: list[dict] = []
    for projection in projections:
        spec = pinned[projection][0]
        for section in components:
            for name, value in spec.get(section, {}).items():
                if name in components[section] and components[section][name] != value:
                    raise GenerationRefused(f"{section}/{name} differs between projections; cannot merge")
                components[section][name] = value
        tags += [t for t in spec.get("tags", []) if t not in tags]

    entries: list[Entry] = []
    objects: dict[tuple[str, str], dict] = {}
    for sel in selected:
        spec, edmx, _ = pinned[sel.op.projection]
        sel.spec_path, sel.spec_op, sel.match = match_spec(sel.op, spec, edmx)
        obj, entry = _operation_object(sel, edmx, stats)
        key = (entry.path, entry.method.lower())
        if key in objects:
            raise GenerationRefused(f"{entry.method} {entry.path} is produced by two operations")
        objects[key] = obj
        entries.append(entry)
    entries.sort(key=lambda e: (e.path, e.method))

    paths: dict[str, dict] = {}
    for path, method in sorted(objects):
        paths.setdefault(path, {})[method] = objects[(path, method)]
    for param in components["parameters"].values():
        stats["links_removed"] += annotate.strip_links(param)
        stats["arrays_converted"] += compat.array_query_to_string(param)
    kept, kept_tags, dangling, dropped = prune.prune(paths, components, tags)
    if dangling:
        raise GenerationRefused("dangling $ref in the pinned $openapi: " + ", ".join(sorted(set(dangling))))
    stats["dropped"] = dropped

    cap_ids = sorted({c for s in selected for c in s.capabilities})
    doc = {
        "swagger": "2.0",
        "info": {"title": package.display_name or package.name,
                 "description": compat.info_description(package.description, cap_ids, projections),
                 "version": package.version},
        "host": PLACEHOLDER_IFS_HOST,
        "basePath": PROJECTION_ROOT,
        "schemes": ["https"],
        "consumes": ["application/json"],
        "produces": ["application/json"],
        "paths": paths,
        **{s: kept[s] for s in ("definitions", "parameters", "responses") if kept[s]},
        "tags": kept_tags,
    }
    errors, size = validate.check(doc, max_bytes)
    if errors:
        raise GenerationRefused("connector checks failed:\n  " + "\n  ".join(errors))

    retired = _check_map(package, entries)
    files = {DEFINITION_FILE: validate.compact(doc) + "\n",
             PROPERTIES_FILE: json.dumps(_properties(), indent=2) + "\n"}
    files[MAP_FILE] = _render_map(package, entries, retired)
    built = Built(files=files, entries=entries, size=size, stats=stats, skipped=skipped, retired=retired)
    files[REPORT_FILE] = _render_report(package, caps, built, pinned)
    return built


def _properties() -> dict:
    # Environment-independent only: authentication (connectionParameters) and the on-premises data gateway
    # are resolved per target by the Phase 10 adapter.
    return {"properties": {"capabilities": [], "connectionParameters": {}, "iconBrandColor": "#007ee5",
                           "policyTemplateInstances": []}}


# ── stable operationId map ───────────────────────────────────────────────────

def _check_map(package: Package, entries: list[Entry]) -> list[str]:
    previous = _read_map(package) or {}
    old = previous.get("operations") or {}
    retired = list(previous.get("retired") or [])
    current = {e.sel.op.id: e.operation_id for e in entries}
    problems = []
    for op_id, oid in current.items():
        if op_id in old and old[op_id]["operation_id"] != oid:
            problems.append(f"{op_id}: operationId would change from {old[op_id]['operation_id']} to {oid}")
        if oid in retired:
            problems.append(f"{op_id}: operationId {oid} was retired and cannot be reused")
        holder = next((o for o, v in old.items() if v["operation_id"] == oid and o != op_id), None)
        if holder:
            problems.append(f"{op_id}: operationId {oid} belongs to {holder}")
    if problems:
        raise GenerationRefused("stable operationId map violated (published flows would break):\n  "
                                + "\n  ".join(problems))
    for op_id, value in old.items():
        if op_id not in current and value["operation_id"] not in retired:
            retired.append(value["operation_id"])
    return sorted(retired)


def _render_map(package: Package, entries: list[Entry], retired: list[str]) -> str:
    data = {"package": package.name, "operations": {}}
    for e in sorted(entries, key=lambda e: e.sel.op.id):
        item = {"operation_id": e.operation_id, "method": e.method, "path": e.path, "revision": e.sel.op.revision}
        if e.params:
            item["parameters"] = dict(e.params)
        data["operations"][e.sel.op.id] = item
    data["retired"] = retired
    return _MAP_HEADER + yaml.safe_dump(data, sort_keys=False, allow_unicode=True)


# ── report ───────────────────────────────────────────────────────────────────

def _render_report(package: Package, caps, built: Built, pinned) -> str:
    used = sorted({c for e in built.entries for c in e.sel.capabilities})
    validated = all(caps[c].runtime_validation.status == "validated" for c in used)
    s = built.stats
    lines = [f"# Connector: {package.display_name or package.name}", "",
             f"Generated by {GENERATOR}; do not edit by hand: "
             f"`ifs-agent-ops connector generate --package {package.name}`.", "",
             "> **Status:** generated from approved capabilities. Runtime validation: "
             + ("**validated**." if validated else "**not deployment-validated** (Phase 11 has not run)."), "",
             "## Operations", "",
             "| operationId | Method | Connector path | Canonical operation | Spec match | Capabilities |",
             "|---|---|---|---|---|---|"]
    for e in built.entries:
        match = e.sel.match + ("" if e.sel.match == "exact" else f" (`{e.sel.spec_path}`)")
        lines.append(f"| `{e.operation_id}` | {e.method} | `{e.path}` | `{e.sel.op.id}` r{e.sel.op.revision} | "
                     f"{match} | {', '.join(e.sel.capabilities)} |")
    lines += ["", "## How values reach IFS", ""]
    literal = [f"`{e.operation_id}`: {', '.join(e.literals)}" for e in built.entries if e.literals]
    if literal:
        lines += ["Function parameters are OData literals sent unquoted (`'text'`, `null`, `Ns.Enum'Member'`, "
                  "numbers, date-times); IFS needs `null` for values a new record does not have yet:", ""]
        lines += [f"- {x}" for x in literal] + [""]
    aliases = [f"`{e.operation_id}`: {', '.join('@' + a for a in e.aliases)}" for e in built.entries if e.aliases]
    if aliases:
        lines += ["Parameter aliases (JSON value in the query string):", ""] + [f"- {x}" for x in aliases] + [""]
    renamed = [f"`{e.operation_id}`: {', '.join(e.renamed)}" for e in built.entries if e.renamed]
    lines += ["Repeated path keys renamed for Power Platform (C1): "
              + ("; ".join(renamed) if renamed else "none") + ".", ""]
    dropped = s["dropped"]
    lines += ["## Transforms and pruning", "",
              f"- Array query options converted to strings (C3): {s['arrays_converted']}",
              f"- `$filter`/`$select` annotations from metadata (C8, C9): {s['annotations']}",
              f"- OData specification links removed: {s['links_removed']}",
              f"- Dropped from the pinned spec (C7): {dropped['definitions']} definitions, {dropped['parameters']} "
              f"parameters, {dropped['responses']} responses, {dropped['tags']} tags", "",
              "## Size (C10)", "",
              f"- `{DEFINITION_FILE}`: {built.size.bytes:,} bytes of {built.size.limit:,} "
              f"({100 * built.size.bytes / built.size.limit:.1f}%)",
              "- Largest paths: " + ", ".join(f"`{p}` ({b:,})" for p, b in built.size.largest_paths),
              "- Largest definitions: " + ", ".join(f"`{d}` ({b:,})" for d, b in built.size.largest_definitions), "",
              "## Resolved at deployment (Phase 10), not generated", "",
              f"- Host: the definition uses the placeholder `{PLACEHOLDER_IFS_HOST}`; the target supplies the real one.",
              "- Connection authentication toward IFS (roadmap section 7, assumption 5) and the on-premises data gateway "
              "(assumption 2): `apiProperties.json` has no `connectionParameters` until then.",
              "- To confirm on import: parameter-alias query names (`@...`) and literal path parameters behave "
              "as recorded.", ""]
    if built.retired:
        lines += ["## Retired operationIds", "", ", ".join(f"`{r}`" for r in built.retired), ""]
    if built.skipped:
        lines += ["## Capabilities not included", "", ", ".join(built.skipped), ""]
    lines += ["## Provenance", "", f"- Package: `{package.name}` {package.version}"]
    for c in used:
        cap = caps[c]
        lines.append(f"- Capability `{c}` revision {cap.revision}, sha256 `{cap.content_hash()}`, approved by "
                     f"{cap.approval.approved_by} at {cap.approval.approved_at}")
    for projection, (_, _, manifest) in sorted(pinned.items()):
        files = manifest.get("files", {})
        lines.append(f"- Metadata `{projection}`: {snap.OPENAPI_FILE} sha256 `{files[snap.OPENAPI_FILE]['sha256']}`, "
                     f"{snap.METADATA_FILE} sha256 `{files[snap.METADATA_FILE]['sha256']}`")
    lines += [f"- Generator: {GENERATOR}", ""]
    return "\n".join(lines)


# ── write ────────────────────────────────────────────────────────────────────

def generate(package: Package, check: bool = False, max_bytes: int = validate.DEFAULT_MAX_BYTES) -> Generation:
    folder = connector_dir(package)
    try:
        existing_map = _read_map(package)
        if existing_map is None:
            for name in (DEFINITION_FILE, PROPERTIES_FILE):
                if (folder / name).exists():
                    raise GenerationRefused(f"{name} exists and was not generated (no {MAP_FILE}); not overwriting it")
        built = build(package, max_bytes)
    except GenerationRefused as exc:
        return Generation([ConnectorResult(folder, "refused", str(exc))], errors=[str(exc)])
    results = []
    for name, text in built.files.items():
        path = folder / name
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == text:
            results.append(ConnectorResult(path, "unchanged"))
        elif check:
            results.append(ConnectorResult(path, "would-create" if old is None else "would-update"))
        else:
            folder.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            results.append(ConnectorResult(path, "created" if old is None else "updated"))
    return Generation(results, built)
